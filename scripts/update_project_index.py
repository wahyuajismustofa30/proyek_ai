#!/usr/bin/env python3
"""Generate the repository project index from actual projects/ directories."""
from __future__ import annotations
import argparse, re, sys
from pathlib import Path

PROJECT_SLUG_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
INDEX_PATH = Path("docs/PROJECT_INDEX.md")

def render_project_index(repository_root: Path) -> str:
    projects_root = repository_root / "projects"
    if not projects_root.is_dir():
        raise ValueError("projects/ directory was not found.")
    project_dirs: list[Path] = []
    for entry in sorted(projects_root.iterdir(), key=lambda item: item.name):
        if entry.is_symlink():
            raise ValueError(f"Symlink entries are not allowed in projects/: {entry.name!r}")
        if entry.is_dir():
            if entry.name.startswith(".") or not PROJECT_SLUG_RE.fullmatch(entry.name):
                raise ValueError(f"Invalid project directory name {entry.name!r}.")
            project_dirs.append(entry)
        elif entry.name != "README.md":
            raise ValueError(f"Only README.md may be stored directly in projects/: {entry.name!r}")
    lines = [
        "# Indeks Proyek", "",
        "<!-- Generated by scripts/update_project_index.py. Do not edit this table manually. -->", "",
        "Daftar ini dibuat dari direktori proyek yang benar-benar tersedia di projects/.",
        "Struktur internal setiap proyek fleksibel; README bersifat opsional.", "",
        "| Proyek | Direktori | README |", "|---|---|---|",
    ]
    if not project_dirs:
        lines.append("| — | — | — |")
    else:
        for project in project_dirs:
            slug = project.name
            name = slug.replace("-", " ").title()
            directory_link = f"[projects/{slug}/](../projects/{slug}/)"
            readme_link = f"[README.md](../projects/{slug}/README.md)" if (project / "README.md").is_file() else "—"
            lines.append(f"| {name} | {directory_link} | {readme_link} |")
    lines.extend([
        "", "## Arsip", "", "archives/ hanya berisi [README penjelas](../archives/README.md).",
        "", "## Penggunaan", "",
        "- Pilih hanya proyek yang diminta pengguna.",
        "- Baca dokumentasi yang tersedia; jangan mengasumsikan file tertentu ada.",
        "- Jika README tidak tersedia, pahami proyek dari struktur, konfigurasi, source, dan dokumentasi yang ada.",
        "- Perbarui indeks dengan python3 scripts/update_project_index.py --write.", "",
    ])
    return "\n".join(lines)

def write_project_index(repository_root: Path) -> Path:
    target = repository_root / INDEX_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_project_index(repository_root), encoding="utf-8")
    return target

def check_project_index(repository_root: Path) -> bool:
    target = repository_root / INDEX_PATH
    return target.is_file() and target.read_text(encoding="utf-8") == render_project_index(repository_root)

def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or verify docs/PROJECT_INDEX.md.")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if args.write:
            target = write_project_index(root)
            print(f"Project index updated: {target.relative_to(root)}")
            return 0
        if check_project_index(root):
            print("Project index is up to date.")
            return 0
        print("Project index is outdated. Run: python3 scripts/update_project_index.py --write", file=sys.stderr)
        return 1
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Project index update failed: {error}", file=sys.stderr)
        return 2

if __name__ == "__main__":
    raise SystemExit(main())
