#!/usr/bin/env python3
"""Generate the curated project index from docs/project-catalog.json."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path, PurePosixPath

INDEX_PATH = Path("docs/PROJECT_INDEX.md")
CATALOG_PATH = Path("docs/project-catalog.json")


def load_catalog(repository_root: Path) -> dict:
    data = json.loads((repository_root / CATALOG_PATH).read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        raise ValueError("Unsupported or invalid project catalog schema.")
    seen: set[str] = set()
    for section in ("projects", "tooling", "categories"):
        if not isinstance(data.get(section), list):
            raise ValueError(f"Catalog section {section!r} must be a list.")
        for item in data[section]:
            if not isinstance(item, dict):
                raise ValueError(f"Entries in {section!r} must be objects.")
            name, raw_path, description = item.get("name"), item.get("path"), item.get("description")
            if not isinstance(name, str) or not name.strip():
                raise ValueError(f"Every {section} entry needs a non-empty name.")
            if not isinstance(description, str) or not description.strip():
                raise ValueError(f"Every {section} entry needs a description.")
            if not isinstance(raw_path, str) or not raw_path:
                raise ValueError(f"Every {section} entry needs a path.")
            path = PurePosixPath(raw_path)
            if path.is_absolute() or ".." in path.parts or not path.parts or path.parts[0] != "projects":
                raise ValueError(f"Unsafe catalog path: {raw_path!r}")
            if any(not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", part) for part in path.parts[1:]):
                raise ValueError(f"Invalid directory slug in catalog path: {raw_path!r}")
            if raw_path in seen:
                raise ValueError(f"Duplicate catalog path: {raw_path!r}")
            seen.add(raw_path)
            target = repository_root.joinpath(*path.parts)
            if target.is_symlink() or not target.is_dir():
                raise ValueError(f"Catalog directory is missing or is a symlink: {raw_path!r}")
            if section == "projects" and not isinstance(item.get("category"), str):
                raise ValueError("Every project entry needs a category.")
    return data


def render_project_index(repository_root: Path) -> str:
    catalog = load_catalog(repository_root)
    lines = [
        "# Indeks Proyek", "",
        "<!-- Generated by scripts/update_project_index.py from docs/project-catalog.json. Do not edit manually. -->", "",
        "Indeks ini memuat proyek yang dipelihara secara eksplisit. Folder kategori dan tooling dicatat terpisah agar tidak keliru dianggap sebagai proyek aplikasi.", "",
        "## Proyek", "",
        "| Proyek | Kategori | Lokasi | Ringkasan | README |",
        "|---|---|---|---|---|",
    ]
    for item in catalog["projects"]:
        path = item["path"]
        readme = repository_root / path / "README.md"
        readme_link = f"[README.md](../{path}/README.md)" if readme.is_file() else "—"
        lines.append(f"| {item['name']} | {item['category']} | [{path}/](../{path}/) | {item['description']} | {readme_link} |")
    lines.extend(["", "## Tooling dan utilitas", "", "| Nama | Lokasi | Fungsi |", "|---|---|---|"])
    for item in catalog["tooling"]:
        path = item["path"]
        lines.append(f"| {item['name']} | [{path}/](../{path}/) | {item['description']} |")
    lines.extend(["", "## Kategori dan wadah", "", "| Kategori | Lokasi | Keterangan |", "|---|---|---|"])
    for item in catalog["categories"]:
        path = item["path"]
        lines.append(f"| {item['name']} | [{path}/](../{path}/) | {item['description']} |")
    lines.extend([
        "", "## Aturan pemeliharaan", "",
        "- docs/project-catalog.json adalah sumber kebenaran daftar proyek, tooling, dan kategori.",
        "- Daftarkan unit kerja yang benar-benar dipelihara; jangan daftarkan folder halaman, aset, atau kategori sebagai proyek.",
        "- Proyek boleh berada di dalam folder kategori, misalnya projects/whatsapp/gowa-gemini-bridge/.",
        "- README bersifat opsional dan ditautkan hanya jika tersedia.",
        "- Setelah mengubah katalog atau struktur, jalankan generator dengan --write lalu verifikasi dengan --check.", ""
    ])
    return "\n".join(lines)


def write_project_index(repository_root: Path) -> Path:
    target = repository_root / INDEX_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_project_index(repository_root), encoding="utf-8")
    return target


def check_project_index(repository_root: Path) -> bool:
    target = repository_root / INDEX_PATH
    return target.is_file() and target.read_text(encoding="utf-8") == render_project_index(repository_root)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or verify docs/PROJECT_INDEX.md.")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if args.write:
            target = write_project_index(root)
            print(f"Project index updated: {target.relative_to(root)}")
            return 0
        if check_project_index(root):
            print("Project index is up to date.")
            return 0
        print("Project index is outdated. Run: python3 scripts/update_project_index.py --write", file=sys.stderr)
        return 1
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError) as error:
        print(f"Project index update failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
